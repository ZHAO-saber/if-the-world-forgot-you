/* 《如果世界忘记了你》— shaders.js
 * 反向显影：颜色先死 → 细节丢失（LOD，真实减少信息量）→ 纸纹潮水吞没 → 潜影。
 * 这不是透明度渐变：它把一张照片在数学上还原成一张没显影的相纸。
 *
 * 性能：所有空间噪声都来自一张预烘焙的 4 通道场纹理 uField（R 潮水A / G 细颗粒 /
 * B 潮水B / A 显影深度），片元着色器里只剩纹理取样和算术，中端手机也能 60fps。
 */
(function (global) {
  'use strict';
  var LX = (global.LX = global.LX || {});

  LX.Shaders = {};

  LX.Shaders.VERT = [
    '#version 300 es',
    'in vec2 aPos;',
    'void main() { gl_Position = vec4(aPos, 0.0, 1.0); }'
  ].join('\n');

  LX.Shaders.FRAG = [
    '#version 300 es',
    'precision highp float;',
    'precision highp sampler2D;',
    '',
    'uniform vec2  uRes;',
    'uniform sampler2D uTable;',
    'uniform sampler2D uCard;',
    'uniform sampler2D uOverlay;',
    'uniform sampler2D uField;',
    'uniform vec4  uCardRect;   // x, y, w, h —— 设备像素，y 自顶部',
    'uniform float uHasCard;',
    'uniform float uHasOverlay;',
    'uniform float uP;          // 删除进度 0..1（JS 端已做非线性）',
    'uniform float uReveal;     // 显影进度 0..1（从底部上涌）',
    'uniform vec3  uCam;        // scale, offsetX, offsetY（相纸 uv 空间）',
    'uniform float uTime;',
    'uniform float uGrain;',
    'uniform float uExposure;   // 结局过曝 0..1',
    'uniform float uGhost;      // 潜影强度（只有最后一个文件留）',
    'uniform float uGhostImg;   // 结局里“她再浮现一次”的余像 0..1',
    'uniform float uSeed;',
    '',
    'out vec4 outColor;',
    '',
    'float hash21(vec2 p, float s) {',
    '  p = fract(p * vec2(123.34, 456.21) + s * 0.017);',
    '  p += dot(p, p + 45.32);',
    '  return fract(p.x * p.y);',
    '}',
    '',
    'void main() {',
    '  vec2 frag = gl_FragCoord.xy;',
    '  vec2 suv = vec2(frag.x / uRes.x, 1.0 - frag.y / uRes.y);   // y 自上',
    '  vec2 devPx = suv * uRes;',
    '',
    '  // ---------------- 桌面相纸 ----------------',
    '  vec2 tblUV = suv * 0.972 + 0.012 + uCam.yz * 0.16;',
    '  vec3 tableCol = texture(uTable, clamp(tblUV, 0.0, 1.0)).rgb;',
    '  float blot = texture(uField, suv * vec2(0.55, 0.68) + 0.11).r;',
    '  tableCol *= 0.984 + 0.032 * blot;',
    '',
    '  vec3 col = tableCol;',
    '  float maskCard = 0.0;',
    '',
    '  // ---------------- 相纸卡片 ----------------',
    '  if (uHasCard > 0.5) {',
    '    vec2 puv = (devPx - uCardRect.xy) / uCardRect.zw;     // 相纸自身坐标，不随呼吸漂',
    '    vec2 cuv = (puv - 0.5) / uCam.x + 0.5 + uCam.yz;      // 画面内容：轻微呼吸',
    '    vec2 tuv = clamp(cuv, 0.0, 1.0);',
    '',
    '    vec4 f0 = texture(uField, clamp(puv * 0.92 + 0.04, 0.0, 1.0));',
    '',
    '    // 相纸形状：圆角矩形 SDF，药膜边随删除被纸纹啃掉',
    '    vec2 q = abs(puv - 0.5) - (0.5 - 0.0045);',
    '    float sd = length(max(q, 0.0)) + min(max(q.x, q.y), 0.0) - 0.0045;',
    '    float feather = 0.0042 + 0.24 * pow(uP, 3.0) + 0.40 * pow(uExposure, 1.5);',
    '    float d2 = sd - (f0.g - 0.5) * feather * 2.6;',
    '    float mask = smoothstep(feather, -feather, d2);',
    '',
    '    // ---------- 显影：从底部上涌 ----------',
    '    float depth = clamp((1.0 - puv.y) * 0.86 + (f0.a - 0.5) * 0.34, 0.0, 1.0);',
    '    float hgt = uReveal * 1.16 - 0.08;',
    '    float den = 1.0 - smoothstep(hgt - 0.040, hgt + 0.040, depth);',
    '',
    '    // ---------- 画面 ----------',
    '    float lod = smoothstep(0.30, 0.90, uP) * 3.0;',
    '    vec3 cardSharp = texture(uCard, tuv).rgb;',
    '    vec3 cardBlur  = textureLod(uCard, tuv, lod).rgb;',
    '    if (uHasOverlay > 0.5) {',
    '      vec4 o1 = texture(uOverlay, tuv);',
    '      vec4 o2 = textureLod(uOverlay, tuv, lod);',
    '      cardSharp = mix(cardSharp, o1.rgb, o1.a);',
    '      cardBlur  = mix(cardBlur,  o2.rgb, o2.a);',
    '    }',
    '',
    '    float L = dot(cardSharp, vec3(0.299, 0.587, 0.114));',
    '',
    '    // (1) 颜色先死：脱色，同时抬黑位（照片不是变暗，是变淡）',
    '    float k1 = smoothstep(0.0, 0.58, uP);',
    '    vec3 gray = vec3(L) * vec3(1.020, 0.995, 0.945);',
    '    gray = gray * (1.0 - 0.46 * k1) + 0.50 * k1;',
    '    cardSharp = mix(cardSharp, gray, k1 * 0.97);',
    '',
    '    // (2) 细节丢失 + 对比塌陷',
    '    vec3 cc = mix(cardSharp, cardBlur, smoothstep(0.30, 0.90, uP) * 0.95);',
    '    cc = mix(cc, tableCol * 1.002, smoothstep(0.58, 1.0, uP) * 0.60);',
    '',
    '    // (3) 纸纹潮水：从四角与边缘吃进来（域扭曲），最后一点由细颗粒啃掉',
    '    vec4 f1 = texture(uField, clamp(puv + (f0.rb - 0.5) * 0.10, 0.0, 1.0));',
    '    float fine = f0.g;',
    '    float edgeBias = length(puv - 0.5) * 1.35;',
    '    float fieldA = f1.r + edgeBias * 0.44 + (fine - 0.5) * 0.26;',
    '    float thA = mix(1.60, -0.30, pow(clamp((uP - 0.50) / 0.50, 0.0, 1.0), 1.5));',
    '    float eatA = smoothstep(thA - 0.02, thA + 0.20, fieldA);',
    '    float wipe = smoothstep(0.80, 1.0, uP) * 1.35 - (fine - 0.5) * 0.45;',
    '    float eat = max(eatA, clamp(wipe, 0.0, 1.0));',
    '    float pg = hash21(floor(puv * vec2(560.0, 760.0)), uSeed + 6.0) - 0.5;',
    '    vec3 paperFill = tableCol + pg * 0.026;',
    '    cc = mix(cc, paperFill, eat);',
    '',
    '    // (4) 颗粒随褪色变粗（银盐不是消失，是变大变稀）',
    '    float gs = mix(760.0, 210.0, uP);',
    '    float gr = hash21(floor(puv * gs), uSeed + 1.0);',
    '    cc -= vec3(0.050, 0.046, 0.038) * (gr - 0.45) * smoothstep(0.52, 1.0, uP);',
    '',
    '    // (5) 潜影：最后几乎全白，但总有一点东西留在纸里',
    '    float ghost = (1.0 - L) * 0.030 * smoothstep(0.55, 1.0, uP) * uGhost;',
    '    cc += vec3(ghost * 0.95, ghost * 0.88, ghost * 0.74);',
    '',
    '    // 还没显影出来的地方就是纸',
    '    cc = mix(tableCol, cc, den);',
    '',
    '    // 结局：照片先慢慢融回纸里（不是压暗成一个矩形），之后整张纸再一起过曝',
    '    cc = mix(cc, tableCol, clamp(uExposure * 2.0, 0.0, 1.0));',
    '',
    '    col = mix(tableCol, cc, mask);',
    '    maskCard = mask;',
    '  }',
    '',
    '  // ---------------- 全局：晕影 + 活的颗粒 ----------------',
    '  vec2 c = suv - 0.5;',
    '  col *= 1.0 - dot(c, c) * 0.20;',
    '  float fn = hash21(frag + floor(uTime * 9.0) * vec2(37.0, 17.0), uSeed + 4.0);',
    '  col += (fn - 0.5) * uGrain;',
    '',
    '  // ---------------- 结局：过曝成白（注意是白，不是黑） ----------------',
    '  // 从画面中心（那点烛光）先烧开，边缘最后；到 1 时全白',
    '  float dc = length((suv - vec2(0.5, 0.48)) * vec2(uRes.x / uRes.y, 1.0));',
    '  float e = clamp(uExposure * 1.30 - dc * 0.22, 0.0, 1.0);',
    '  col = mix(col, vec3(1.0, 0.9995, 0.9975), e);',
    '',
    '  // ---------------- 余像：白光里她再浮现一次（不是照片，是压痕） ----------------',
    '  if (uGhostImg > 0.002 && uHasCard > 0.5) {',
    '    vec2 gv = (devPx - uCardRect.xy) / uCardRect.zw;',
    '    vec2 g0 = clamp(gv, 0.0, 1.0);',
    '    vec2 ex = vec2(2.5 / 1024.0, 2.5 / 1408.0);',
    '    vec3 s0 = textureLod(uCard, g0, 1.5).rgb;',
    '    vec3 sx = textureLod(uCard, clamp(g0 + vec2(ex.x, 0.0), 0.0, 1.0), 1.5).rgb;',
    '    vec3 sy = textureLod(uCard, clamp(g0 + vec2(0.0, ex.y), 0.0, 1.0), 1.5).rgb;',
    '    float l0 = dot(s0, vec3(0.299, 0.587, 0.114));',
    '    float lx = dot(sx, vec3(0.299, 0.587, 0.114));',
    '    float ly = dot(sy, vec3(0.299, 0.587, 0.114));',
    '    float edg = clamp((abs(l0 - lx) + abs(l0 - ly)) * 2.6, 0.0, 1.0);',
    '    float gm = smoothstep(0.68, 0.30, length(gv - 0.5));',
    '    float fill = clamp((0.74 - l0) * 0.30, 0.0, 0.18);',
    '    col -= vec3(0.058, 0.054, 0.047) * (edg * 1.25 + fill) * gm * uGhostImg;',
    '  }',
    '',
    '  outColor = vec4(clamp(col, 0.0, 1.0), 1.0);',
    '}'
  ].join('\n');
})(window);
